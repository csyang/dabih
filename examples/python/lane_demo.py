"""
examples/python/lane_demo.py
~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Three worked hardware examples demonstrating coverage compression.

Example 1:  3-lane interface  — S3 lane symmetry
Example 2:  8-lane interface  — S8 lane symmetry (large group, big gains)
Example 3:  4-stage pipeline  — partial symmetry (only mid-stages equivalent)
Example 4:  Cross-scenario    — value class bins × lane state (2D compression)

Run:  python examples/python/lane_demo.py
"""

import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))

from dabih.core.coverpoint import Coverpoint
from dabih.core.symmetry import Permutation
from dabih.core.bin_space import BinSpace


# ── Shared bin definitions ────────────────────────────────────────────────────

LANE_STATES = ["IDLE", "ACTIVE", "STALL", "ERROR"]

PIPELINE_STATES = ["EMPTY", "FILLING", "FULL", "FLUSHING"]

VALUE_CLASSES = ["ZERO", "ONE_HOT", "BOUNDARY_LO", "BOUNDARY_HI",
                 "INTERIOR", "ALL_ONES"]


# ─────────────────────────────────────────────────────────────────────────────
# Example 1: 3-lane interface, full S3 symmetry
# ─────────────────────────────────────────────────────────────────────────────

def example_3_lane():
    print("\n" + "▓" * 64)
    print("  EXAMPLE 1: 3-Lane Interface — Full S3 Symmetry")
    print("▓" * 64)
    print("""
  RTL context:
    generate for (genvar i = 0; i < 3; i++) begin : lane
      rx_lane u (.state(lane_state[i]), ...);
    end endgenerate

  Covergroup (without Dabih):
    coverpoint lane0_state  { bins s[] = { IDLE, ACTIVE, STALL, ERROR }; }
    coverpoint lane1_state  { bins s[] = { IDLE, ACTIVE, STALL, ERROR }; }
    coverpoint lane2_state  { bins s[] = { IDLE, ACTIVE, STALL, ERROR }; }
    cross lane0_state, lane1_state, lane2_state;  // 4^3 = 64 bins

  Symmetry claim:
    Lane i and lane j are structurally identical — permuting lane
    indices leaves observable behavior invariant.  Group: S3 (order 6).
""")

    bs = BinSpace(name="3-lane interface / S3")
    for i in range(3):
        bs.add_coverpoint(Coverpoint.from_names(f"lane{i}_state", LANE_STATES))

    # S3 generated by: swap(0,1) and 3-cycle(0→1→2→0)
    bs.add_full_lane_symmetry(n_lanes=3)

    print(bs.report())

    # Show the expansion logic
    print("\n  Coverage Expansion Demo:")
    print("  Suppose simulation hits these representative bins:")
    reps = bs.select_representatives()
    hit_reps = {reps[0], reps[3], reps[7]}
    for r in sorted(hit_reps):
        print(f"    {bs.bin_label(r)}")

    stats = bs.coverage_stats(hit_reps)
    print(f"\n  → {stats['classes_hit']} of {stats['classes_total']} classes hit")
    print(f"  → Implies {stats['bins_implied_covered']} of "
          f"{stats['bins_total']} bins covered "
          f"({stats['bin_coverage_pct']:.1f}%)")



# Example 4: 2D compression — lane state × value class
# ─────────────────────────────────────────────────────────────────────────────

def example_2d_compression():
    print("\n" + "▓" * 64)
    print("  EXAMPLE 4: 2D Compression — Lane Symmetry × Value Classes")
    print("▓" * 64)
    print("""
  Combining two orthogonal sources of compression:
    Axis 1: 3 symmetric lanes (structural — S3)
    Axis 2: 6 value equivalence classes per lane (behavioral)

  Naïve cross coverage: 3 lanes × 6 value classes → 6^3 = 216 bins.
  Both compressions apply independently and multiplicatively.
""")

    bs = BinSpace(name="3-lane / value classes / S3")
    for i in range(3):
        bs.add_coverpoint(Coverpoint.value_class_bins(f"lane{i}_data"))

    bs.add_full_lane_symmetry(n_lanes=3)

    print(bs.report(max_orbits=20))

    print("\n  Breakdown of compression sources:")
    print(f"  Value class reduction alone:  6^3=216 → {(6*7*8)//6} bins  (3.00×)")
    # multisets of size 3 from 6 = C(8,3) = 56
    orbits = bs.compute_orbits()
    print(f"  After S3 lane symmetry added: 216 → {len(orbits)} bins"
          f"  ({bs.compression_ratio():.2f}×)")


# ─────────────────────────────────────────────────────────────────────────────
# Scaling table
# ─────────────────────────────────────────────────────────────────────────────

def scaling_table():
    print("\n" + "▓" * 64)
    print("  SCALING TABLE: S_n Compression on 4-bin coverpoints")
    print("▓" * 64)
    print(f"\n  {'Lanes':>6}  {'Raw bins':>12}  {'Orbits':>8}  {'Ratio':>8}  {'Eliminated':>10}")
    print("  " + "-" * 52)

    for n_lanes in [2, 3, 4, 5, 6, 8]:
        bs = BinSpace()
        for i in range(n_lanes):
            bs.add_coverpoint(Coverpoint.from_names(f"lane{i}", LANE_STATES))
        bs.add_full_lane_symmetry(n_lanes=n_lanes)

        total = bs.total_bin_count()
        n_orbits = bs.orbit_count()
        ratio = bs.compression_ratio()
        elim = bs.compression_pct()
        print(f"  {n_lanes:>6}  {total:>12,}  {n_orbits:>8,}  {ratio:>7.1f}×  {elim:>9.1f}%")



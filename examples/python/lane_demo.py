def example_8_lane():
    print("\n" + "▓" * 64)
    print("  EXAMPLE 2: 8-Lane Interface — Full S8 Symmetry")
    print("▓" * 64)
    print("""
  RTL context:
    Parameterized 8-lane PCIe / SerDes / memory channel array.
    generate for (genvar i = 0; i < 8; i++) begin : ch
      channel u (.state(ch_state[i]), ...);
    end endgenerate

  Naïve cross coverage: 4^8 = 65,536 bins
  S8 has order 40,320 — exhaustive group enumeration avoided;
  orbit BFS uses only 2 generators.
""")

    bs = BinSpace(name="8-lane interface / S8")
    for i in range(8):
        bs.add_coverpoint(Coverpoint.from_names(f"ch{i}_state", LANE_STATES))

    bs.add_full_lane_symmetry(n_lanes=8)

    print(bs.report(max_orbits=15))

    # The orbit count for multisets of size 8 from 4 symbols = C(11,3) = 165
    orbits = bs.compute_orbits()
    print(f"\n  Mathematical check: C(n+k-1, k) = C(4+8-1, 8) = C(11,3) = 165")
    print(f"  Computed orbit count: {len(orbits)}  ✓" if len(orbits) == 165 else
          f"  Computed orbit count: {len(orbits)}")


# ─────────────────────────────────────────────────────────────────────────────
# Example 3: 4-stage pipeline — partial symmetry (mid-stages only)
# ─────────────────────────────────────────────────────────────────────────────

def example_pipeline_partial_symmetry():
    print("\n" + "▓" * 64)
    print("  EXAMPLE 3: 4-Stage Pipeline — Partial Symmetry")
    print("▓" * 64)
    print("""
  RTL context:
    stage0: fetch  (unique — PC logic, branch prediction)
    stage1: decode (symmetric with stage2)
    stage2: execute (symmetric with stage1)
    stage3: writeback (unique — register file write)

  Only stages 1 and 2 are behaviorally equivalent.
  Symmetry group: {identity, swap(1,2)}  — order 2.
""")

    bs_full = BinSpace(name="4-stage pipeline / full symmetry (baseline)")
    bs_partial = BinSpace(name="4-stage pipeline / partial symmetry")

    stage_names = ["stage0_fetch", "stage1_decode", "stage2_execute", "stage3_wb"]
    for name in stage_names:
        bs_full.add_coverpoint(Coverpoint.from_names(name, PIPELINE_STATES))
        bs_partial.add_coverpoint(Coverpoint.from_names(name, PIPELINE_STATES))

    # Full symmetry (wrong — stages are not all equivalent): S4
    bs_full.add_full_lane_symmetry(n_lanes=4)

    # Correct partial symmetry: only stages 1 and 2
    bs_partial.add_symmetry([0, 2, 1, 3])  # swap coverpoints 1 and 2

    print("\n  --- Baseline: no symmetry ---")
    bs_none = BinSpace(name="4-stage pipeline / no symmetry")
    for name in stage_names:
        bs_none.add_coverpoint(Coverpoint.from_names(name, PIPELINE_STATES))
    orbits_none = bs_none.compute_orbits()
    total = bs_none.total_bin_count()
    print(f"  Total bins: {total:,}   Orbits: {len(orbits_none):,}   Ratio: 1.00×")

    print("\n  --- Correct partial symmetry: swap(stage1, stage2) ---")
    orbits_partial = bs_partial.compute_orbits()
    print(f"  Total bins: {total:,}   Orbits: {len(orbits_partial):,}"
          f"   Ratio: {bs_partial.compression_ratio():.2f}×"
          f"   ({bs_partial.compression_pct():.1f}% eliminated)")

    print("\n  --- Over-claimed full S4 symmetry (incorrect for this design) ---")
    orbits_full = bs_full.compute_orbits()
    print(f"  Total bins: {total:,}   Orbits: {len(orbits_full):,}"
          f"   Ratio: {bs_full.compression_ratio():.2f}×")
    print("  ⚠ Warning: full S4 symmetry is unsound — stage0/stage3 are unique.")
    print("    Dabih's Idea D (formal verification pass) would catch this.")


